import { describe, it, expect } from 'vitest';
import { SMS_WELCOME_TEXT, SMS_MESSAGE_TYPES, smsWorkOrderAssigned } from '@/lib/smsProgram';

describe('SMS program', () => {
  it('opt-in confirmation carries the disclosures carriers require', () => {
    expect(SMS_WELCOME_TEXT).toContain('Precision Lift Co.');
    expect(SMS_WELCOME_TEXT).toMatch(/Msg frequency varies/);
    expect(SMS_WELCOME_TEXT).toMatch(/Msg & data rates may apply/);
    expect(SMS_WELCOME_TEXT).toMatch(/HELP/);
    expect(SMS_WELCOME_TEXT).toMatch(/STOP/);
  });

  it('public examples are generated by the same functions the app sends with', () => {
    const assigned = SMS_MESSAGE_TYPES.find(t => t.label === 'Work order assigned');
    expect(assigned?.example).toBe(smsWorkOrderAssigned('Monday, Nov 3 at 9:00 AM'));
    expect(SMS_MESSAGE_TYPES[0].example).toBe(SMS_WELCOME_TEXT);
  });
});
